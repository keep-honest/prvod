const MAX_COMMENT_JSON_CHARS = 60_000;

function formatScriptBlock(scriptJson: unknown): string {
  const json = JSON.stringify(scriptJson, null, 2);
  const truncated = json.length > MAX_COMMENT_JSON_CHARS
    ? json.slice(0, MAX_COMMENT_JSON_CHARS) + "\n... (truncated)"
    : json;
  return "```json\n" + truncated + "\n```";
}

function buildScriptReadyComment(scriptJson: unknown | null): string {
  return [
    "### 🎬 PrVod",
    "",
    "Script generated! The PR analysis script is ready.",
    "",
    scriptJson ? formatScriptBlock(scriptJson) : "_No script output available_",
    "",
    "---",
    "*Generated by [PrVod](https://prvod.dev)*",
  ].join("\n");
}

