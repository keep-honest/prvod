// Validates repoFullName matches the owner/repo format before URL construction
const REPO_FULL_NAME_REGEX = /^[a-zA-Z0-9._-]+\/[a-zA-Z0-9._-]+$/;
const RECEIVED_RETRY_AFTER_MS = 5 * 60 * 1000;

