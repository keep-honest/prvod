function isBotAuthoredIssueComment(comment: Record<string, unknown> | undefined): boolean {
  const user = (comment?.user as Record<string, unknown> | undefined) ?? undefined;
  const commenterLogin = (user?.login as string | undefined) ?? "";
  const commenterType = (user?.type as string | undefined) ?? "";
  const appSlug = (process.env.GITHUB_APP_SLUG ?? "").trim();
  const performedViaApp = comment?.performed_via_github_app as
    | Record<string, unknown>
    | undefined;
  const performedViaSlug = ((performedViaApp?.slug as string | undefined) ?? "").trim();

  // Debug context shared by every return path below. The bot guard silently
  // returning `false` on our own comment was the direct cause of a webhook
  // loop (https://prvod.dev internal) — logging the fields that feed into
  // the decision lets us diagnose any future miss without adding more round
  // trips. Sensitive data is not present on this payload.
  const guardContext = {
    commenterLogin,
    commenterType,
    appSlug: appSlug || "<unset>",
    performedViaSlug: performedViaSlug || "<none>",
  };

  if (commenterType.toLowerCase() === "bot") {
    logger.debug("Bot guard hit: commenter type is 'Bot'", guardContext);
    return true;
  }
  if (commenterLogin.endsWith("[bot]")) {
    logger.debug("Bot guard hit: commenter login ends with [bot]", guardContext);
    return true;
  }
  if (appSlug && commenterLogin === `${appSlug}[bot]`) {
    logger.debug("Bot guard hit: commenter login matches appSlug[bot]", guardContext);
    return true;
  }
  if (appSlug && performedViaSlug === appSlug) {
    logger.debug("Bot guard hit: performed_via_github_app.slug matches appSlug", guardContext);
    return true;
  }

  // Only log misses when the comment looks remotely bot-ish to avoid flooding
  // the logs with real user comments. A miss in any of these cases is worth
  // investigating because it's how we ended up in the loop originally.
  if (
    commenterType ||
    commenterLogin.includes("bot") ||
    commenterLogin.includes("[") ||
    performedViaSlug
  ) {
    logger.debug("Bot guard miss — comment processed as human", guardContext);
  }
  return false;
}

